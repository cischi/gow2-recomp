"""gen_import_stubs.py <ppc_recomp_shared.h> <out.cpp> [--implemented-from <dir>]...

Generates a stub for every kernel/XAM import declared by XenonRecomp and not
yet implemented.

XenonRecomp declares the imports in ppc_recomp_shared.h like the other functions,
`PPC_EXTERN_FUNC(__imp__Name);` (the name comes from the symbol ParseImage creates
for each function thunk), and the recompiled code calls them directly
(`__imp__Name(ctx, base);`) or through the function table. The runtime must therefore
define all of them. Those implemented in runtime/kernel/ are declared with
`KERNEL_EXPORT(Name, HostFunction)` (runtime/kernel/registry.h): with
`--implemented-from <dir>` they are searched in all the .cpp files of <dir> (subfolders
included) and no stub is generated for those names; the option can be repeated
(runtime/kernel, runtime/gpu and runtime/gpu_fake) and the names found add up. Every other stub, with --trace
on, writes `[kernel] Name(r3=..., ..., r10=...)` with LogImport; it always
goes through kernel::stats::NoteUnimplemented with one static slot per stub
(`static kernel::stats::UnimplementedSlot s_slot{"Name"};`: hot path
without locks or allocations; the first call writes
`[kernel] UNIMPLEMENTED Name(r3=..., ..., r10=...)`, all of them are counted for the
summary) and returns 0 in r3.

Ordinals without a name in the XenonUtils tables do not become `__imp__`
symbols (XenonRecomp treats them as normal `sub_` functions), so they do not
appear here.

Exit 0 if the output was written; 1 if the header is missing, unreadable or
contains no imports, or if a --implemented-from folder (or one of its .cpp files) cannot be
read; 2 for incorrect usage.
"""

import argparse
import re
import sys
from pathlib import Path

# Format emitted by XenonRecomp (recompiler.cpp, SaveCurrentOutData /
# ppc_recomp_shared.h): one declaration per line.
_DECL_RE = re.compile(r"^\s*PPC_EXTERN_FUNC\(__imp__(\w+)\);", re.MULTILINE)
# __imp__sub_XXXXXXXX are the implementations of the recompiled functions, not imports.
_IMPL_RE = re.compile(r"^sub_[0-9A-Fa-f]{8}$")
# Implementations in runtime/kernel/: KERNEL_EXPORT(Name, HostFunction) or
# KERNEL_EXPORT_RAW(Name) { PPC body } (registry.h).
_EXPORT_RE = re.compile(r"KERNEL_EXPORT(?:_RAW)?\(\s*(\w+)")

_USAGE = "usage: gen_import_stubs.py <ppc_recomp_shared.h> <out.cpp> [--implemented-from <dir>]..."


def parse_imports(header: str) -> list[str]:
    """Names (without `__imp__`) of the declared imports, in order and without duplicates."""
    seen: dict[str, None] = {}
    for name in _DECL_RE.findall(header):
        if not _IMPL_RE.match(name):
            seen.setdefault(name, None)
    return list(seen)


def implemented_names(sources: list[str]) -> set[str]:
    """Names declared with KERNEL_EXPORT(Name, ...) in the source text."""
    names: set[str] = set()
    for text in sources:
        names.update(_EXPORT_RE.findall(text))
    return names


def read_implemented(directory: Path) -> set[str]:
    """implemented_names of all the .cpp files under `directory`; OSError if they cannot be read."""
    if not directory.is_dir():
        raise FileNotFoundError(2, "folder does not exist", str(directory))
    return implemented_names([p.read_text(encoding="utf-8") for p in sorted(directory.rglob("*.cpp"))])


def generate(names: list[str], implemented: set[str] | frozenset[str] = frozenset()) -> str:
    out = [
        "// Generated by tools/gen_import_stubs.py: do not edit.",
        "// Stubs for the kernel/XAM imports not implemented in runtime/kernel/:",
        "// they count the call (logged the first time) and return 0 in r3.",
        '#include "ppc_recomp_shared.h"',
        '#include "recomp_glue.h"',
        '#include "kernel/stats.h"',
        "",
    ]
    for name in names:
        if name in implemented:
            continue
        out += [
            f"PPC_FUNC(__imp__{name}) {{",
            f'  static kernel::stats::UnimplementedSlot s_slot{{"{name}"}};',
            f'  if (kernel::stats::Trace()) LogImport("{name}", ctx);',
            "  kernel::stats::NoteUnimplemented(s_slot, ImportRegs(ctx));",
            "  ctx.r3.u64 = 0;",
            "}",
            "",
        ]
    return "\n".join(out)


class _Parser(argparse.ArgumentParser):
    def error(self, message: str):
        print(f"{_USAGE}\n({message})", file=sys.stderr)
        sys.exit(2)


def main(argv: list[str]) -> int:
    parser = _Parser(add_help=False)
    parser.add_argument("header", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--implemented-from", type=Path, action="append", default=[])
    args = parser.parse_args(argv[1:])
    header, out = args.header, args.out
    implemented: set[str] = set()
    for directory in args.implemented_from:
        try:
            implemented |= read_implemented(directory)
        except OSError as e:
            print(f"gen_import_stubs: cannot read {e.filename}: {e.strerror}", file=sys.stderr)
            return 1
    try:
        text = header.read_text(encoding="utf-8")
    except OSError as e:
        print(f"gen_import_stubs: cannot read {header}: {e.strerror}", file=sys.stderr)
        return 1
    names = parse_imports(text)
    if not names:
        print(f"gen_import_stubs: no imports (PPC_EXTERN_FUNC(__imp__...)) in {header}", file=sys.stderr)
        return 1
    content = generate(names, implemented)
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        # no rewrite if identical: avoids needless recompilations
        if not out.is_file() or out.read_text(encoding="utf-8") != content:
            out.write_text(content, encoding="utf-8", newline="\n")
    except OSError as e:
        print(f"gen_import_stubs: cannot write {out}: {e.strerror}", file=sys.stderr)
        return 1
    stubs = sum(1 for n in names if n not in implemented)
    print(f"gen_import_stubs: stubs: {stubs} ({len(names) - stubs} imports implemented) -> {out}")
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv))
